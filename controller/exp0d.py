# ----------------------------------------------------------------------------------------------- helpers
def now_iso() -> str:
    t = time.time()
    return time.strftime("%Y-%m-%dT%H:%M:%S", time.gmtime(t)) + ".%03dZ" % int((t % 1) * 1000)


def log(msg: str) -> None:
    sys.stderr.write(f"{now_iso()} {msg}\n")
    sys.stderr.flush()


def load_json(path: Path, default):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        return default
    except (OSError, ValueError) as e:
        log(f"cannot read {path}: {e}")
        return default


def save_json(path: Path, obj, mode: int = 0o600) -> None:
    tmp = path.with_name(path.name + ".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=1, sort_keys=True)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def merged(default: dict, loaded) -> dict:
    out = json.loads(json.dumps(default))
    if isinstance(loaded, dict):
        for k, v in loaded.items():
            if isinstance(out.get(k), dict) and isinstance(v, dict):
                out[k].update(v)
            else:
                out[k] = v
    return out


_DIRECT = urllib.request.build_opener(urllib.request.ProxyHandler({}))


def http_json(method: str, url: str, headers: dict | None = None, body=None, form: dict | None = None,
              timeout: float = 10.0):
    """Returns (status, obj). status 0 = network failure. Loopback URLs never go through a proxy."""
    h = {"Accept": "application/json", "User-Agent": "exp0/" + VERSION}
    if headers:
        h.update(headers)
    data = None
    if form is not None:
        data = urllib.parse.urlencode(form).encode()
        h["Content-Type"] = "application/x-www-form-urlencoded"
    elif body is not None:
        data = json.dumps(body).encode()
        h["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=data, method=method, headers=h)
    opener = _DIRECT if urllib.parse.urlsplit(url).hostname in LOOPBACK_HOSTS else urllib.request.build_opener()
    try:
        with opener.open(req, timeout=timeout) as r:
            status, raw = r.status, r.read()
    except urllib.error.HTTPError as e:
        status, raw = e.code, e.read()
    except (urllib.error.URLError, OSError, ValueError) as e:
        return 0, {"error": f"{type(e).__name__}: {e}"}
    if not raw:
        return status, {}
    try:
        obj = json.loads(raw)
        return status, obj if isinstance(obj, dict) else {"data": obj}
    except ValueError:
        return status, {"raw": raw[:300].decode("utf-8", "replace")}


