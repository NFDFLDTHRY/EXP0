def running_pid():
    try:
        pid = int(PID_PATH.read_text().strip())
    except (OSError, ValueError):
        return None
    try:
        os.kill(pid, 0)
    except OSError:
        return None
    try:
        cmd = Path(f"/proc/{pid}/cmdline").read_bytes().split(b"\0")
        if not any(p.endswith(b"exp0d.py") for p in cmd) or b"run" not in cmd:
            return None
    except OSError:
        pass
    return pid


