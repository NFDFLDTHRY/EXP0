def make_handler(ctrl: Controller):
    port = ctrl.config["port"]
    hosts = {f"127.0.0.1:{port}", f"localhost:{port}", f"[::1]:{port}"}

    class Handler(http.server.BaseHTTPRequestHandler):
        server_version = "exp0d"
        sys_version = ""
        protocol_version = "HTTP/1.1"

        def log_message(self, *args):
            pass

        def _reply(self, status: int, obj: dict, origin: str | None = None) -> None:
            body = json.dumps(obj).encode()
            self.send_response(status)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            if origin:
                self.send_header("Access-Control-Allow-Origin", origin)
                self.send_header("Vary", "Origin")
            self.end_headers()
            self.wfile.write(body)

        def _check(self):
            if self.headers.get("Host", "") not in hosts:
                return None, (403, {"error": "bad_host"})
            origin = self.headers.get("Origin")
            if origin is not None and origin not in ALLOWED_ORIGINS:
                return None, (403, {"error": "origin_not_allowed"})
            return origin, None

        def do_OPTIONS(self):
            origin, err = self._check()
            if err or not origin:
                self.send_response(403)
                self.send_header("Content-Length", "0")
                self.end_headers()
                return
            self.send_response(204)
            self.send_header("Access-Control-Allow-Origin", origin)
            self.send_header("Vary", "Origin")
            self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
            self.send_header("Access-Control-Allow-Headers", "Authorization, Content-Type")
            self.send_header("Access-Control-Max-Age", "600")
            if self.headers.get("Access-Control-Request-Private-Network") == "true":
                self.send_header("Access-Control-Allow-Private-Network", "true")
            self.send_header("Content-Length", "0")
            self.end_headers()

        def _handle(self, method: str) -> None:
            n = int(self.headers.get("Content-Length") or 0)
            if n > 65536:
                self.close_connection = True
                return self._reply(413, {"error": "too_large"})
            raw = self.rfile.read(n) if n else b""
            origin, err = self._check()
            if err:
                return self._reply(*err)
            u = urllib.parse.urlsplit(self.path)
            if method == "GET" and u.path == "/v1/health":
                return self._reply(200, {"ok": True, "exp0": VERSION, "role": ctrl.config["role"]}, origin)
            auth = self.headers.get("Authorization", "")
            if not (auth.startswith("Bearer ") and hmac.compare_digest(auth[7:].encode(), ctrl.key.encode())):
                return self._reply(401, {"error": "bad_session_key",
                                         "hint": "open the ally link printed by ./exp0 start or ./exp0 status"}, origin)
            try:
                body = json.loads(raw) if raw else {}
            except ValueError:
                return self._reply(400, {"error": "bad_json"}, origin)
            if not isinstance(body, dict):
                return self._reply(400, {"error": "bad_json"}, origin)
            fn = ROUTES.get((method, u.path))
            if not fn:
                return self._reply(404, {"error": "no_route"}, origin)
            try:
                return self._reply(200, fn(ctrl, body, urllib.parse.parse_qs(u.query)) or {"ok": True}, origin)
            except ApiError as e:
                return self._reply(e.status, {"error": e.error}, origin)
            except Exception as e:
                ctrl.hist.append("error", {"op": "api_exception", "path": u.path, "error": f"{type(e).__name__}: {e}"})
                return self._reply(500, {"error": "internal", "detail": str(e)[:200]}, origin)

        def do_GET(self):
            self._handle("GET")

        def do_POST(self):
            self._handle("POST")

    return Handler


