class History:
    """APPEND-ONLY HISTORY: one NDJSON file, never rewritten. seq continues across restarts."""

    def __init__(self, path: Path):
        self.path = path
        self.lock = threading.Lock()
        self.ok = True
        self.seq = self._last_seq()

    def _last_seq(self) -> int:
        try:
            with open(self.path, "rb") as f:
                f.seek(0, 2)
                size = f.tell()
                f.seek(max(0, size - 65536))
                lines = f.read().splitlines()
        except FileNotFoundError:
            return 0
        for line in reversed(lines):
            try:
                return int(json.loads(line)["seq"])
            except (ValueError, KeyError, TypeError):
                continue
        return 0

    def append(self, kind: str, data: dict, ref: dict | None = None) -> int:
        with self.lock:
            self.seq += 1
            rec = {"seq": self.seq, "t": now_iso(), "kind": kind, "data": data}
            if ref:
                rec["ref"] = {k: v for k, v in ref.items() if v is not None}
            line = json.dumps(rec, separators=(",", ":"), ensure_ascii=False) + "\n"
            try:
                fd = os.open(self.path, os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
                with os.fdopen(fd, "a", encoding="utf-8") as f:
                    f.write(line)
                    f.flush()
                    os.fsync(f.fileno())
                self.ok = True
            except OSError as e:
                self.ok = False
                log(f"HISTORY WRITE FAILED: {e}")
            return self.seq

    def tail(self, after: int = 0, limit: int = 200) -> list:
        with self.lock:
            try:
                with open(self.path, "rb") as f:
                    f.seek(0, 2)
                    size = f.tell()
                    f.seek(max(0, size - 2_000_000))
                    data = f.read()
            except FileNotFoundError:
                return []
        out = []
        for line in data.splitlines():
            try:
                rec = json.loads(line)
            except ValueError:
                continue
            if isinstance(rec, dict) and rec.get("seq", 0) > after:
                out.append(rec)
        return out[-limit:]


# ----------------------------------------------------------------------------------------------- websocket
class WSClosed(Exception):
    def __init__(self, msg: str, code: int | None = None):
        super().__init__(msg)
        self.code = code


class WSClient:
    """Minimal RFC 6455 client (text/binary, fragmentation, ping/pong, close). Enough for EventSub."""

    GUID = "258EAFA5-E914-47DA-95CA-C5AB0DC85B11"

    def __init__(self, url: str, timeout: float = 15.0):
        u = urllib.parse.urlsplit(url)
        if u.scheme not in ("ws", "wss") or not u.hostname:
            raise ValueError(f"not a websocket url: {url}")
        secure = u.scheme == "wss"
        port = u.port or (443 if secure else 80)
        path = (u.path or "/") + (("?" + u.query) if u.query else "")
        sock = socket.create_connection((u.hostname, port), timeout=timeout)
        if secure:
            sock = ssl.create_default_context().wrap_socket(sock, server_hostname=u.hostname)
        self.sock = sock
        self.buf = b""
        self.closed = False
        self.send_lock = threading.Lock()
        self.frag_op = None
        self.frag: list = []
        key = base64.b64encode(os.urandom(16)).decode()
        hostport = u.hostname if port == (443 if secure else 80) else f"{u.hostname}:{port}"
        req = (f"GET {path} HTTP/1.1\r\nHost: {hostport}\r\nUpgrade: websocket\r\nConnection: Upgrade\r\n"
               f"Sec-WebSocket-Key: {key}\r\nSec-WebSocket-Version: 13\r\nUser-Agent: exp0/{VERSION}\r\n\r\n")
        sock.sendall(req.encode("ascii"))
        while b"\r\n\r\n" not in self.buf:
            chunk = sock.recv(4096)
            if not chunk:
                raise WSClosed("eof during handshake", 1006)
            self.buf += chunk
            if len(self.buf) > 65536:
                raise WSClosed("handshake too large")
        head, _, self.buf = self.buf.partition(b"\r\n\r\n")
        lines = head.decode("latin-1").split("\r\n")
        parts = lines[0].split(" ", 2)
        if len(parts) < 2 or parts[1] != "101":
            raise WSClosed("handshake refused: " + lines[0])
        hdrs = {}
        for line in lines[1:]:
            if ":" in line:
                k, v = line.split(":", 1)
                hdrs[k.strip().lower()] = v.strip()
        accept = base64.b64encode(hashlib.sha1((key + self.GUID).encode()).digest()).decode()
        if hdrs.get("sec-websocket-accept") != accept:
            raise WSClosed("bad Sec-WebSocket-Accept")

    def _try_frame(self):
        b = self.buf
        if len(b) < 2:
            return None
        fin, opcode = b[0] & 0x80, b[0] & 0x0F
        masked, ln, i = b[1] & 0x80, b[1] & 0x7F, 2
        if ln == 126:
            if len(b) < 4:
                return None
            ln, i = struct.unpack(">H", b[2:4])[0], 4
        elif ln == 127:
            if len(b) < 10:
                return None
            ln, i = struct.unpack(">Q", b[2:10])[0], 10
        if ln > 16 * 1024 * 1024:
            raise WSClosed("frame too large", 1009)
        mask = None
        if masked:
            if len(b) < i + 4:
                return None
            mask, i = b[i:i + 4], i + 4
        if len(b) < i + ln:
            return None
        payload = b[i:i + ln]
        if mask:
            payload = bytes(x ^ mask[j % 4] for j, x in enumerate(payload))
        self.buf = b[i + ln:]
        return bool(fin), opcode, payload

    def recv(self, timeout: float):
        """(opcode, payload) of one complete message, or None on timeout."""
        deadline = time.monotonic() + timeout
        while True:
            fr = self._try_frame()
            if fr is None:
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    return None
                self.sock.settimeout(remaining)
                try:
                    chunk = self.sock.recv(65536)
                except (socket.timeout, TimeoutError):
                    return None
                if not chunk:
                    self.closed = True
                    raise WSClosed("connection lost", 1006)
                self.buf += chunk
                continue
            fin, op, payload = fr
            if op == 0x9:
                self._send(0xA, payload)
                continue
            if op == 0xA:
                continue
            if op == 0x8:
                code = struct.unpack(">H", payload[:2])[0] if len(payload) >= 2 else 1005
                reason = payload[2:].decode("utf-8", "replace")
                try:
                    self._send(0x8, payload[:2])
                except OSError:
                    pass
                self.closed = True
                try:
                    self.sock.close()
                except OSError:
                    pass
                raise WSClosed(f"closed by server: {code} {reason}".strip(), code)
            if op in (0x1, 0x2):
                if fin:
                    return op, payload
                self.frag_op, self.frag = op, [payload]
                continue
            if op == 0x0 and self.frag_op is not None:
                self.frag.append(payload)
                if fin:
                    op0, data = self.frag_op, b"".join(self.frag)
                    self.frag_op, self.frag = None, []
                    return op0, data
                continue
            raise WSClosed(f"protocol error: opcode {op}", 1002)

    def _send(self, opcode: int, payload: bytes = b"") -> None:
        header = bytearray([0x80 | opcode])
        n = len(payload)
        if n < 126:
            header.append(0x80 | n)
        elif n < 65536:
            header.append(0x80 | 126)
            header += struct.pack(">H", n)
        else:
            header.append(0x80 | 127)
            header += struct.pack(">Q", n)
        mask = os.urandom(4)
        header += mask
        body = bytes(x ^ mask[i % 4] for i, x in enumerate(payload))
        with self.send_lock:
            self.sock.settimeout(10)
            self.sock.sendall(bytes(header) + body)

    def close(self, code: int = 1000, reason: str = "") -> None:
        if self.closed:
            return
        self.closed = True
        try:
            self._send(0x8, struct.pack(">H", code) + reason.encode()[:120])
        except OSError:
            pass
        try:
            self.sock.close()
        except OSError:
            pass


# ----------------------------------------------------------------------------------------------- edge
class Edge:
    """TWITCH BOUNDARY: EventSub WebSocket session, subscriptions, reconnects. Terminates Twitch structures."""

    def __init__(self, c: "Controller"):
        self.c = c
        self.thread: threading.Thread | None = None
        self.stop_evt = threading.Event()
        self.connected = False
        self.session_id = None
        self.subs: dict = {}
        self.error = None
        self.last_msg = 0.0
        self.keepalive = 30
        self.ws: WSClient | None = None
        self.reconnects = 0
        self.session_ok = False

    def running(self) -> bool:
        return bool(self.thread and self.thread.is_alive())

    def start(self) -> bool:
        if self.running() and self.stop_evt.is_set():
            self.thread.join(5)  # a previous session is still winding down
        if self.running():
            return False
        self.stop_evt.clear()
        self.error = None
        self.reconnects = 0
        self.thread = threading.Thread(target=self._run, name="edge", daemon=True)
        self.thread.start()
        return True

    def stop(self, wait: bool = True) -> None:
        self.stop_evt.set()
        ws = self.ws
        if ws:
            ws.close(1000, "stop")
        if wait and self.thread and self.thread is not threading.current_thread():
            self.thread.join(5)
        self.connected = False

    def _run(self) -> None:
        c = self.c
        backoff = 1.0
        c.hist.append("session", {"op": "edge_start"})
        while not self.stop_evt.is_set():
            if not c.revalidate(max_age=0 if self.reconnects else 60):
                c.auth_invalid("token not valid at (re)connect")
                break
            self.session_ok = False
            url = TWITCH_EVENTSUB + ("&" if "?" in TWITCH_EVENTSUB else "?") + "keepalive_timeout_seconds=30"
            try:
                self._session(url)
            except WSClosed as e:
                self.error = str(e)
                c.hist.append("session", {"op": "ws_closed", "reason": str(e), "code": e.code})
            except (OSError, ValueError, KeyError, TypeError) as e:
                self.error = f"{type(e).__name__}: {e}"
                c.hist.append("session", {"op": "ws_error", "error": self.error})
            self.connected = False
            self.session_id = None
            for s in self.subs.values():
                if s.get("status") == "enabled":
                    s["status"] = "disconnected"
            if self.stop_evt.is_set():
                break
            if self.session_ok:
                backoff = 1.0
            self.reconnects += 1
            c.hist.append("session", {"op": "reconnect_scheduled", "in_s": backoff,
                                      "note": "external actions refused until the connection is valid again"})
            if self.stop_evt.wait(backoff):
                break
            backoff = min(backoff * 2, 60.0)
        self.connected = False
        c.hist.append("session", {"op": "edge_stopped"})

    def _expect_welcome(self, ws: WSClient) -> dict:
        deadline = time.time() + 15
        while time.time() < deadline and not self.stop_evt.is_set():
            m = ws.recv(1.0)
            if m is None:
                continue
            self.last_msg = time.time()
            msg = json.loads(m[1].decode("utf-8"))
            if (msg.get("metadata") or {}).get("message_type") == "session_welcome":
                return msg["payload"]["session"]
            self.c.hist.append("error", {"op": "unexpected_before_welcome", "message_type": (msg.get("metadata") or {}).get("message_type")})
        raise WSClosed("no session_welcome within 15s")

    def _session(self, url: str) -> None:
        c = self.c
        ws = WSClient(url)
        self.ws = ws
        try:
            w = self._expect_welcome(ws)
            self.session_id = w["id"]
            self.keepalive = int(w.get("keepalive_timeout_seconds") or 30)
            c.hist.append("session", {"op": "welcome", "session_id": self.session_id,
                                      "keepalive_timeout_seconds": self.keepalive})
            self._subscribe_all()
            enabled = [k for k, s in self.subs.items() if s.get("status") == "enabled"]
            if not enabled:
                raise WSClosed("no subscription was accepted")
            self.connected = True
            self.session_ok = True
            with c.lock:
                c.tests["eventsub"] = {"ok": True, "at": now_iso(), "session_id": self.session_id,
                                       "subs": {k: s.get("status") for k, s in self.subs.items()}}
            while not self.stop_evt.is_set():
                tok = c.token
                if not tok or not tok.get("valid"):
                    raise WSClosed("authentication invalid")
                if time.time() - self.last_msg > self.keepalive + 5:
                    c.hist.append("session", {"op": "keepalive_timeout", "silence_s": round(time.time() - self.last_msg, 1)})
                    raise WSClosed("keepalive timeout", 4005)
                m = ws.recv(1.0)
                if m is None:
                    continue
                self.last_msg = time.time()
                try:
                    msg = json.loads(m[1].decode("utf-8"))
                except ValueError:
                    c.hist.append("error", {"op": "unknown_input", "reason": "not json"})
                    continue
                t = (msg.get("metadata") or {}).get("message_type")
                if t == "session_keepalive":
                    continue
                if t == "notification":
                    c.on_notification(msg)
                elif t == "session_reconnect":
                    ws = self._reconnect(ws, msg)
                elif t == "revocation":
                    sub = (msg.get("payload") or {}).get("subscription") or {}
                    for s in self.subs.values():
                        if s.get("id") == sub.get("id"):
                            s["status"] = "revoked:" + str(sub.get("status"))
                    c.hist.append("session", {"op": "revocation", "subscription_id": sub.get("id"),
                                              "type": sub.get("type"), "status": sub.get("status")})
                    if not any(s.get("status") == "enabled" for s in self.subs.values()):
                        raise WSClosed("all subscriptions revoked")
                else:
                    c.hist.append("error", {"op": "unknown_input", "message_type": t, "note": "logged and ignored"})
        finally:
            ws.close(1000, "bye")
            self.ws = None

    def _subscribe_all(self) -> None:
        c = self.c
        tok = c.token or {}
        me = tok.get("user_id")
        scopes = tok.get("scopes") or []
        wanted = [("own_chat", "channel.chat.message", {"broadcaster_user_id": me, "user_id": me})]
        opp = c.config.get("opponent_id")
        if opp and opp != me:
            wanted.append(("opponent_chat", "channel.chat.message", {"broadcaster_user_id": opp, "user_id": me}))
        if "user:manage:whispers" in scopes or "user:read:whispers" in scopes:
            wanted.append(("whispers", "user.whisper.message", {"user_id": me}))
        subs = {}
        for key, typ, cond in wanted:
            body = {"type": typ, "version": "1", "condition": cond,
                    "transport": {"method": "websocket", "session_id": self.session_id}}
            st, b = c.helix("POST", "/eventsub/subscriptions", body)
            d = b.get("data")[0] if isinstance(b.get("data"), list) and b.get("data") else {}
            rec = {"type": typ, "condition": cond, "http": st, "id": d.get("id"),
                   "status": d.get("status") if st == 202 else "failed",
                   "error": None if st == 202 else (b.get("message") or b.get("error"))}
            subs[key] = rec
            c.hist.append("session", {"op": "subscribe", "key": key, **rec})
        self.subs = subs

    def _reconnect(self, old: WSClient, msg: dict) -> WSClient:
        c = self.c
        url = ((msg.get("payload") or {}).get("session") or {}).get("reconnect_url")
        c.hist.append("session", {"op": "reconnect_requested", "note": "old connection kept until the new one says welcome"})
        new = WSClient(url)
        w = self._expect_welcome(new)
        while True:  # drain what the old connection still delivered
            try:
                m = old.recv(0.2)
            except WSClosed:
                break
            if m is None:
                break
            try:
                om = json.loads(m[1].decode("utf-8"))
            except ValueError:
                continue
            if (om.get("metadata") or {}).get("message_type") == "notification":
                c.on_notification(om)
        old.close(1000, "reconnected")
        self.ws = new
        self.session_id = w["id"]
        self.keepalive = int(w.get("keepalive_timeout_seconds") or self.keepalive)
        c.hist.append("session", {"op": "reconnected", "session_id": self.session_id,
                                  "note": "subscriptions carried over by Twitch; not recreated"})
        return new


