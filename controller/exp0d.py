def cmd_init(argv: list) -> int:
    role, port = "all-in-one", None
    it = iter(argv)
    for a in it:
        if a == "--role":
            role = next(it, role)
        elif a == "--port":
            port = int(next(it))
    VAR.mkdir(parents=True, exist_ok=True)
    os.chmod(VAR, 0o700)
    cfg = read_config()
    cfg["role"] = role
    if port:
        if not 1024 <= port <= 65535:
            print("  FAIL  port must be 1024-65535")
            return 2
        cfg["port"] = port
    save_json(CONFIG_PATH, cfg)
    print(f"  PASS  config: {CONFIG_PATH} (role {role}, port {cfg['port']}, opponent {cfg['opponent_login']})")
    return 0


def cmd_run() -> int:
    VAR.mkdir(parents=True, exist_ok=True)
    os.chmod(VAR, 0o700)
    c = Controller()
    port = c.config["port"]
    try:
        srv = Server(("127.0.0.1", port), make_handler(c))
    except OSError as e:
        c.hist.append("error", {"op": "bind_failed", "port": port, "error": str(e)})
        log(f"cannot bind 127.0.0.1:{port}: {e}")
        c.close()
        return 2
    fd = os.open(KEY_PATH, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    os.write(fd, c.key.encode())
    os.close(fd)
    PID_PATH.write_text(str(os.getpid()))

    def on_signal(signum, _frame):
        c.hist.append("control", {"op": "controller_stop", "signal": signum})
        threading.Thread(target=srv.shutdown, daemon=True).start()

    signal.signal(signal.SIGTERM, on_signal)
    signal.signal(signal.SIGINT, on_signal)
    log(f"exp0d {VERSION} listening on 127.0.0.1:{port} (loopback only)")
    try:
        srv.serve_forever(poll_interval=0.5)
    finally:
        c.close()
        srv.server_close()
        for p in (KEY_PATH, PID_PATH):
            try:
                p.unlink()
            except OSError:
                pass
        log("exp0d stopped")
    return 0


def port_in_use(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.settimeout(0.5)
        return s.connect_ex(("127.0.0.1", port)) == 0


def cmd_start() -> int:
    if not CONFIG_PATH.exists():
        print("not set up: run ./setup.sh first")
        return 2
    cfg = read_config()
    pid = running_pid()
    if pid:
        print(f"already running (pid {pid})")
        return cmd_status()
    if port_in_use(cfg["port"]):
        print(f"port {cfg['port']} on 127.0.0.1 is used by another program. Pick another: ./setup.sh --port N")
        return 2
    for p in (KEY_PATH, PID_PATH):
        try:
            p.unlink()
        except OSError:
            pass
    logf = open(LOG_PATH, "ab")
    proc = subprocess.Popen([sys.executable, str(Path(__file__).resolve()), "run"], cwd=str(ROOT),
                            stdin=subprocess.DEVNULL, stdout=logf, stderr=logf, start_new_session=True)
    deadline = time.time() + 10
    while time.time() < deadline:
        if proc.poll() is not None:
            print("controller exited during start - see ./exp0 logs")
            return 1
        if KEY_PATH.exists() and local_get(cfg["port"], "/v1/health", timeout=0.5)[0] == 200:
            break
        time.sleep(0.1)
    else:
        print("controller did not become healthy within 10s - see ./exp0 logs")
        return 1
    key = KEY_PATH.read_text().strip()
    print(f"EXP0 controller running: 127.0.0.1:{cfg['port']} (loopback only), pid {proc.pid}, role {cfg['role']}")
    print("Open ally.html with this link (everything after # stays in your browser):")
    print("  " + ally_link(cfg, key))
    return 0


def cmd_stop() -> int:
    pid = running_pid()
    if not pid:
        print("not running")
        return 0
    os.kill(pid, signal.SIGTERM)
    deadline = time.time() + 10
    while time.time() < deadline:
        try:
            os.kill(pid, 0)
        except OSError:
            print(f"stopped (pid {pid})")
            return 0
        time.sleep(0.1)
    os.kill(pid, signal.SIGKILL)
    print(f"killed (pid {pid}) after 10s")
    return 0


